import { build } from "esbuild";
import { writeFile } from "node:fs/promises";
// The complete kernel runs inside QuickJS, not as host callbacks into Node or the page.
const { outputFiles } = await build({
  stdin: {
    contents:
      'export { default as modeling } from "@jscad/modeling"; export { default as stl } from "@jscad/stl-serializer";',
    resolveDir: process.cwd()
  },
  bundle: true,
  write: false,
  format: "iife",
  globalName: "cadLibraries",
  platform: "browser",
  target: "es2020",
  minify: true,
  legalComments: "eof"
});
await writeFile(
  "src/software/cad/runtime-source.generated.ts",
  `// Generated by scripts/build-cad-runtime.mjs.\nexport const runtimeSource = ${JSON.stringify(outputFiles[0].text)};\n`
);

// Ship API help from the installed kernel, so Agent guidance matches execution exactly.
const { readFile, readdir } = await import("node:fs/promises");
const { join, relative, basename } = await import("node:path");
const { default: modeling } = await import("@jscad/modeling");
const kernelRoot = "node_modules/@jscad/modeling/src";
async function declarationsIn(directory) {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await declarationsIn(path)));
    else if (entry.name.endsWith(".d.ts")) {
      const declarations = await readFile(path, "utf8");
      const source = await readFile(path.replace(/\.d\.ts$/, ".js"), "utf8").catch(() => "");
      files.push({
        path: relative(directory, path),
        fullPath: path,
        declarations,
        documentation: (source.match(/\/\*\*[\s\S]*?\*\//g) ?? []).join("\n")
      });
    }
  }
  return files;
}
const apiReference = {};
const entry = await readFile(join(kernelRoot, "index.d.ts"), "utf8");
for (const match of entry.matchAll(/export \* as (\w+) from '([^']+)'/g)) {
  const [, name, location] = match;
  const directory = join(kernelRoot, location);
  const files = await declarationsIn(directory);
  apiReference[name] = {};
  for (const member of Object.keys(modeling[name])) {
    const named = new RegExp(`(?:function|const|class)\\s+${member}\\b`);
    apiReference[name][member] = files
      .filter(
        (file) =>
          basename(file.fullPath, ".d.ts") === member ||
          relative(directory, file.fullPath).split("/")[0] === member ||
          named.test(file.declarations)
      )
      .map(({ fullPath, declarations, documentation }) => ({
        path: relative(kernelRoot, fullPath),
        declarations,
        documentation
      }));
  }
}
await writeFile(
  "src/software/cad/api-reference.generated.ts",
  `// Generated from @jscad/modeling declarations and API comments.\nexport const apiReference: Record<string, Record<string, Array<{path:string;declarations:string;documentation:string}>>> = ${JSON.stringify(apiReference)};\n`
);
